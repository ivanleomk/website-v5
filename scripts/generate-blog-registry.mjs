import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const contentDir = path.join(root, "src/content/blog");
const outputPath = path.join(contentDir, "registry.ts");

function slugify(text) {
  return text
    .toLowerCase()
    .replace(/[^\w\s-]/g, "")
    .replace(/\s+/g, "-");
}

function parseHeadings(raw) {
  const headings = [];
  for (const line of raw.split("\n")) {
    const match = line.match(/^(#{2,3})\s+(.+)$/);
    if (!match) {
      continue;
    }

    headings.push({
      text: match[2].trim(),
      id: slugify(match[2].trim()),
      level: match[1].length,
    });
  }
  return headings;
}

function toIdentifier(slug, suffix) {
  const base = slug
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, char) => char.toUpperCase())
    .replace(/^[^a-zA-Z_]+/, "");
  return `${base || "post"}${suffix}`;
}

const files = fs
  .readdirSync(contentDir)
  .filter((file) => file.endsWith(".mdx"))
  .sort();

const imports = [];
const posts = [];

for (const file of files) {
  const slug = file.replace(/\.mdx$/, "");
  const raw = fs.readFileSync(path.join(contentDir, file), "utf8");
  const contentIdentifier = toIdentifier(slug, "Content");
  const frontmatterIdentifier = toIdentifier(slug, "Frontmatter");

  imports.push(
    `import ${contentIdentifier}, { frontmatter as ${frontmatterIdentifier} } from "./${file}";`
  );
  posts.push(`  {
    slug: ${JSON.stringify(slug)},
    frontmatter: ${frontmatterIdentifier},
    Content: ${contentIdentifier},
    headings: ${JSON.stringify(parseHeadings(raw), null, 4).replace(/\n/g, "\n    ")},
  }`);
}

const output = `// This file is generated by scripts/generate-blog-registry.mjs.
// Do not edit it directly.

import type { ComponentType } from "react";
import type { MDXComponents } from "mdx/types";
${imports.join("\n")}

export type BlogFrontmatter = {
  title?: string;
  date?: string;
  description?: string;
  author?: string;
  cover?: string;
};

export type BlogHeading = {
  text: string;
  id: string;
  level: number;
};

export type BlogPost = {
  slug: string;
  frontmatter: BlogFrontmatter;
  Content: ComponentType<{ components?: MDXComponents }>;
  headings: BlogHeading[];
};

export const blogPosts: BlogPost[] = [
${posts.join(",\n")}
];

export function getBlogPost(slug: string) {
  return blogPosts.find((post) => post.slug === slug);
}
`;

fs.writeFileSync(outputPath, output);
